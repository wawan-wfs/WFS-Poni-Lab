from playwright.sync_api import expect


def test_dashboard(page):
    page.locator('.tab[data-page="dashboard"]').click()
    dashboard = page.locator('#page-dashboard')
    slots = dashboard.locator('select')
    cards = dashboard.locator('.dashboard-card')
    expect(cards).to_have_count(4)
    expect(cards.first).to_have_attribute('data-widget', 'clock')
    save = dashboard.get_by_role('button', name='Save widgets')
    expect(save).to_be_enabled()
    slots.nth(0).select_option('todo')
    save.click()
    expect(dashboard.get_by_role('status')).to_contain_text('different widget')
    slots.nth(0).select_option('system')
    slots.nth(1).select_option('media')
    save.click()
    expect(cards.nth(0)).to_contain_text('CPU · 33%')
    expect(cards.nth(1)).to_contain_text('Test track')
    cards.nth(1).get_by_role('button', name='Next').click()
    assert page.evaluate("localStorage.getItem('last-media-action')") == 'next'
    cards.nth(0).get_by_role('button', name='System').click()
    expect(page.locator('#page-system')).to_be_visible()
    page.reload()
    page.locator('#closed').dispatch_event('pointerenter')
    page.locator('.tab[data-page="dashboard"]').click()
    expect(slots.nth(0)).to_have_value('system')
    expect(slots.nth(1)).to_have_value('media')
    expect(cards.nth(0)).to_contain_text('Memory · 25%')
    slots.nth(2).select_option('weather')
    slots.nth(3).select_option('pomodoro')
    save.click()
    expect(cards.nth(2)).to_contain_text('30°C')
    expect(cards.nth(2)).to_contain_text('H 32°')
    expect(cards.nth(3)).to_contain_text('25:00')
